-- DSS_GetObjectHeader
--------------------------------------------------------------------------------------------------------
-- This function will create a standardized header for automaticly generated objects.
--------------------------------------------------------------------------------------------------------
create function [app].[DimEngine_GetObjectHeader]
(
	@Generator varchar(512),
	@ObjectType varchar(100),
	@Description varchar(max) = null
) 
returns varchar(max)
as
begin
	declare @NewLine char(2)
	set @NewLine = char(13) + char(10)

	declare @Header varchar(max)
	select @Header = 
		'--------------------------------------------------------------------------------------------------' + @NewLine +
		'-- AUTOMATICLY GENERATED ' + upper(@ObjectType) + @NewLine +
		'--------------------------------------------------------------------------------------------------' + @NewLine +
		'-- Generated by:	' + @Generator + @NewLine +
		'-- Generated at:	' + convert(varchar(20), getdate(), 120)+ @NewLine +
		'--------------------------------------------------------------------------------------------------' + @NewLine
		--case 
		--	when @Description is not null then
		--		@Description + @NewLine +
		--		'--------------------------------------------------------------------------------------------------' + @NewLine
		--	else
		--		''
		--end
		
		if @Description is not null
			begin
				select @Description = replace(@Description, @NewLine, char(13))
				
				select
					@Header = @Header +
						'-- ' + Item + @NewLine
				from
					app.Split(@Description, char(13))
			
			
				select @Header = @Header +
					'--------------------------------------------------------------------------------------------------' + @NewLine
			end
		

	return @Header
end
GO
